import { ChevronLeft, ChevronRight } from 'lucide-react'
import { useState } from 'react'
import { Link } from 'react-router'
import { Alert, Card, PageHeader, Spinner, buttonStyles } from '../components/ui'
import { useApiQuery } from '../hooks/useApiQuery'
import { ApiError, apiRequest, toQuery } from '../lib/api'
import { formatDateTime } from '../lib/format'
import type { NotificationRead, Page } from '../types'

export default function NotificationsPage() {
  const [unreadOnly, setUnreadOnly] = useState(false)
  const [page, setPage] = useState(1)
  const [key, setKey] = useState(0)
  const [error, setError] = useState<string | null>(null)
  const result = useApiQuery<Page<NotificationRead>>(`/notifications${toQuery({ unread_only: unreadOnly, page, page_size: 20, k: key })}`)
  const data = result.data

  async function run(path: string) {
    setError(null)
    try {
      await apiRequest(path, { method: 'POST' })
      setKey((k) => k + 1)
    } catch (err) {
      setError(err instanceof ApiError ? err.message : 'Action failed.')
    }
  }

  return (
    <div className="space-y-5">
      <PageHeader
        title="Notifications"
        description="Alerts generated by events on records you are allowed to see."
        actions={
          <>
            <label className="flex items-center gap-2 text-sm text-slate-700">
              <input type="checkbox" checked={unreadOnly} onChange={(e) => { setUnreadOnly(e.target.checked); setPage(1) }} /> Unread only
            </label>
            <button type="button" className={buttonStyles.secondary} onClick={() => run('/notifications/read-all')}>Mark all read</button>
          </>
        }
      />
      {error && <Alert tone="error">{error}</Alert>}
      {result.status === 'error' && (
        <Alert tone="error" title="Could not load notifications" action={<button type="button" className={buttonStyles.secondary} onClick={result.reload}>Try again</button>}>
          {result.error.message}
        </Alert>
      )}
      {result.status === 'loading' && !data && <Spinner label="Loading notifications…" />}
      {data && data.total === 0 && <Card className="p-10 text-center text-sm text-slate-600">{unreadOnly ? 'No unread notifications.' : 'No notifications yet.'}</Card>}
      {data && data.total > 0 && (
        <Card>
          <ul className="divide-y divide-slate-100">
            {data.items.map((n) => (
              <li key={n.id} className={`flex flex-wrap items-start gap-3 px-4 py-3 ${n.read_at ? '' : 'bg-sky-50/60'}`}>
                <div className="min-w-0 flex-1">
                  <p className="text-sm font-medium text-slate-900">{n.title}</p>
                  <p className="text-sm text-slate-600">{n.body}</p>
                  <p className="mt-0.5 text-xs text-slate-400">{formatDateTime(n.created_at)}{n.read_at && ' · read'}</p>
                </div>
                <div className="flex gap-2">
                  {n.link && <Link to={n.link} onClick={() => !n.read_at && run(`/notifications/${n.id}/read`)} className={buttonStyles.secondary}>Open</Link>}
                  {!n.read_at && <button type="button" className={buttonStyles.secondary} onClick={() => run(`/notifications/${n.id}/read`)}>Mark read</button>}
                </div>
              </li>
            ))}
          </ul>
          <div className="flex items-center justify-between border-t border-slate-200 px-4 py-3 text-sm text-slate-600">
            <span>{data.total} notification{data.total === 1 ? '' : 's'}</span>
            <div className="flex gap-2">
              <button type="button" className={buttonStyles.secondary} disabled={page <= 1} onClick={() => setPage(page - 1)}><ChevronLeft className="size-4" /> Previous</button>
              <button type="button" className={buttonStyles.secondary} disabled={page >= data.pages} onClick={() => setPage(page + 1)}>Next <ChevronRight className="size-4" /></button>
            </div>
          </div>
        </Card>
      )}
    </div>
  )
}
